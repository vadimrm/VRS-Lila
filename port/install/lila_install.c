{
static int hgt[3][320];
int lay,x,z,icol,h1,h2;
int layercol[3]={33,25,20};//цвет слоя: дальний бледный -> ближний темный
int snowcol[3]={54,54,52};
//высотные линии хребтов: дальний слой выше (у горизонта z~72),
//ближние ниже; крупный шум - плавные широкие вершины
for (lay=0; lay<3; ++lay)
  for (x=0; x<320; ++x)
    hgt[lay][x]=(lay==0? 75: lay==1? 95: 118)
                + (fbm(x/4+lay*97,lay*31,2)-20)*(lay==0? 2: 3);
for (z=0; z<200; ++z)
  for (x=0; x<320; ++x)
    {
    //небо: от зенита к горизонту светлеет
    if (z<100) icol=10+(z*5)/100;
    else       icol=16+(z-100)*6/100;
    //слои хребтов (дальний рисуется первым, ближний перекрывает)
    for (lay=0; lay<3; ++lay)
      {
      h1=hgt[lay][x];
      if (z>=h1)
        {
        h2=hgt[lay][(x+1)&319];
        //на склоне: чем дальше от вершины, тем светлее (дымка)
        icol=layercol[lay]+(z-h1)/10;
        if (icol>layercol[lay]+6) icol=layercol[lay]+6;
        //снег на вершинах дальнего и среднего слоев
        if (lay<2 && z<h1+8+(h2-h1)/4) icol=snowcol[lay];
        }
      }
    //у земли - зелень
    if (z>170) icol=40+(z-170)/4;
    tex[z*320+x]=(byte)icol;
    }
}

//запись pp-файла
static void WritePP(char *fname,byte *tex,byte *pal)
{
FILE *f;
if ((f=fopen(fname,"wb"))==NULL)
  {
  printf("file create error (%s) !\n",fname);
  exit(4);
  }
fwrite(tex,1,PPTEXLEN,f);
fwrite(pal,1,PAL768,f);
//прозрачный цвет -1 и цветность 1 - формат как у WriteScreen()
fprintf(f,"\r\n\r\n -1\r\n  1\r\n");
fclose(f);
printf("file save (%s, %li bytes) !\n\n",fname,(long)(PPTEXLEN+PAL768+9+5));
}

//палитра небесных оттенков (10-15 небо, 16-55 облака от серых к белым)
static void PalSky(byte *pal)
{
int i,r,g,b;
for (i=0; i<256; ++i)
  {
  if (i<16)      { r=2;  g=6+i;  b=44-i;                  }//небо
  else if (i<56) { r=30+((i-16)*26)/40; g=32+((i-16)*26)/40;
                   b=42+((i-16)*18)/40;                   }//облака
  else           { r=56; g=58; b=60;                      }//белое
  if (r>63) r=63; if (g>63) g=63; if (b>63) b=63;
  pal[i*3]  =(byte)r;
  pal[i*3+1]=(byte)g;
  pal[i*3+2]=(byte)b;
  }
}

//палитра горных оттенков (небо/дымка/три слоя хребтов/зелень/снег)
static void PalMount(byte *pal)
{
int i,r,g,b;
for (i=0; i<256; ++i)
  {
  if (i<16)      { r=2;  g=6+i;  b=44-i;                 }//небо
  else if (i<20) { r=36; g=40; b=46;                     }//дымка у горизонта
  else if (i<27) { r=12; g=18+(i-20)*2; b=14;            }//ближний хребет
  else if (i<32) { r=24; g=28+(i-27)*2; b=32;            }//средний хребет
  else if (i<40) { r=34; g=38+(i-33)*2; b=44;            }//дальний хребет
  else if (i<48) { r=10+(i-40)/2; g=38+(i-40); b=12;     }//зелень
  else           { r=56; g=56; b=58;                     }//снег
  if (r>63) r=63; if (g>63) g=63; if (b>63) b=63;
  pal[i*3]  =(byte)r;
  pal[i*3+1]=(byte)g;
  pal[i*3+2]=(byte)b;
  }
}

static void PPSave(void)
{
static byte tex[PPTEXLEN];
static byte pal[PAL768];

printf("Comput PP\\far0.pp (clouds) ... ");
PalSky(pal);
GenClouds(tex);
WritePP("PP\\far0.pp",tex,pal);

printf("Comput PP\\far1.pp (mountains) ... ");
PalMount(pal);
GenMountains(tex);
WritePP("PP\\far1.pp",tex,pal);
}

