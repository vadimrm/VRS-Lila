/*------------------------------------------------------------
  Процедурные pp-картинки дали (опция --pp).
  Формат pp: 64000 байт текстуры 320x200 (мода 1: сверху вниз),
  768 байт палитры VGA (0..63), хвост "\r\n\r\n -1\r\n  1\r\n"
  (прозрачный цвет -1, цветность 1) - как в WriteScreen().
*/

#define PPTEXLEN 64000
#define PAL768   768

//быстрый хэш-шум для процедурных картинок
static dword nzseed;
static int nzrand(void)
{
nzseed=nzseed*0x015a4e35L+1;
return (int)((nzseed>>16)&0x7fff);
}

//значение шума в точке (билинейная интерполяция решетки 128x128)
static int noisefield(int x,int y)
{
static int grid[129][129];
static int inited=NO;
int gx,gy,fx,fy,v00,v10,v01,v11;
if (!inited)
  {
  nzseed=12345;
  for (gy=0; gy<129; ++gy)
    for (gx=0; gx<129; ++gx)
      grid[gy][gx]=nzrand()%64;
  inited=YES;
  }
x&=1023; y&=1023;//защита от выхода за решетку при масштабировании
gx=x>>3; gy=y>>3; fx=x&7; fy=y&7;
v00=grid[gy][gx]; v10=grid[gy][gx+1];
v01=grid[gy+1][gx]; v11=grid[gy+1][gx+1];
return (v00*(8-fx)*(8-fy)+v10*fx*(8-fy)+v01*(8-fx)*fy+v11*fx*fy)>>6;
}

//многоктавный шум
static int fbm(int x,int y,int oct)
{
int v=0,a=8,i;
for (i=0; i<oct; ++i)
  {
  v+=noisefield(x,y)*a;
  x<<=1; y<<=1; a>>=1;
  }
return v>>4;
}

//текстура облаков: небо сверху и снизу, мягкая полоса облаков у горизонта
static void GenClouds(byte *tex)
{
int x,z,i,c,d;
for (z=0; z<200; ++z)
  for (x=0; x<320; ++x)
    {
    //небо: сверху насыщенно-синее, к горизонту светлее, ниже - дымка
    if (z<100) i=10+(z*5)/100;         //10..15 к горизонту
    else       i=16+(z-100)*8/100;     //16..23 дымка вниз
    //облака: крупный мягкий шум, вытянутый по горизонтали,
    //плотность максимальна у горизонта (z~100)
    d=fbm(x/4,z/2+7,3)*2-46;           //редкие плотные ядра облаков
    c=100-z; if (c<0) c=-c;
    c=36-(c*36)/100;                   //профиль облачности 0..36
    if (d>0 && c>0)
      {
      d=(d*c)/36;
      i=16+(d*39)/40;
      }
    if (i>55) i=55;
    tex[z*320+x]=(byte)i;
    }
}

